def q_text(q):
    return f"{q['kz']} / {q['ru']}"


def build_xlsx():
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Sheet1"
    head = ["Question Text", "Question Type", "Option 1", "Option 2", "Option 3",
            "Option 4", "Option 5", "Correct Answer", "Time in seconds", "Image Link"]
    ws.append(head)
    for c in ws[1]:
        c.font = Font(bold=True)
    for q in QUESTIONS:
        opts = q["options"] + [""] * (5 - len(q["options"]))
        ws.append([
            q_text(q),
            "Multiple Choice" if q["type"] == "mc" else "Checkbox",
            *opts,
            ",".join(map(str, q["correct"])),
            q["time"],
            "",
        ])
    widths = [70, 16, 34, 34, 34, 34, 8, 14, 14, 10]
    for i, w in enumerate(widths):
        ws.column_dimensions[chr(65 + i)].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
    wb.save(HERE / "wayground_import.xlsx")


def build_guide():
    L = []
    L.append("# ЖИ-детектив / ИИ-детектив — шпаргалка ведущего\n")
    L.append("Семинар: «Жасанды интеллект заманындағы мектеп кітапханасы: Жаңа мүмкіндіктер мен сын-қатерлер»\n")
    L.append("## Сценарий (15 минут)\n")
    L.append("| Время | Что делает ведущий |\n|---|---|")
    L.append("| 0:00–2:00 | Запустить игру в Wayground (Live), показать код/QR на экране. Участники заходят с телефона на **joinmyquiz.com** |")
    L.append("| 2:00–5:30 | Раунд 1 «Факт или миф?» — вопросы 1–4 (по 30 с) |")
    L.append("| 5:30–8:30 | Раунд 2 «Найди фейк» — вопросы 5–7 (по 45 с) |")
    L.append("| 8:30–11:30 | Раунд 3 «Что сделает библиотекарь?» — вопросы 8–10 (по 45 с) |")
    L.append("| 11:30–15:00 | Таблица лидеров, награждение, 3 правила (ниже) |\n")
    L.append("После каждого вопроса — 1 фраза из пояснения (не больше 15 секунд).\n")
    for ri, (rkz, rru) in enumerate(ROUNDS):
        L.append(f"## {rkz} / {rru}\n")
        for i, q in enumerate(QUESTIONS, 1):
            if q["round"] != ri:
                continue
            L.append(f"### {i}. {q['kz']}\n*{q['ru']}*\n")
            for n, o in enumerate(q["options"], 1):
                mark = " ✅" if n in q["correct"] else ""
                L.append(f"{n}. {o}{mark}")
            L.append("")
            L.append(f"**ҚАЗ:** {q['ex_kz']}\n")
            L.append(f"**РУС:** {q['ex_ru']}\n")
            L.append("Источник: " + "; ".join(q["src"]) + "\n")
    L.append("## Финал: 3 правила / 3 ереже\n")
    for kz, ru in RULES:
        L.append(f"- **{kz}**  \n  {ru}")
    L.append("")
    (HERE / "host_guide.md").write_text("\n".join(L), encoding="utf-8")


def build_html():
    data = json.dumps(dict(q=QUESTIONS, rounds=ROUNDS, rules=RULES), ensure_ascii=False)
    tpl = (HERE / "backup_template.html").read_text(encoding="utf-8")
    (HERE / "backup.html").write_text(tpl.replace("/*DATA*/null", data), encoding="utf-8")


if __name__ == "__main__":
    build_xlsx()
    build_guide()
    build_html()
    print("ok")
